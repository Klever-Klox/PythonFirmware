def bitmap(data):
    bmp = displayio.Bitmap(W, H, 2)
    for y in range(H):
        for x in range(W):
            if data[y * 3 + x // 8] & (0x80 >> (x % 8)):
                bmp[x, y] = 1
    return bmp


class Icon:
    """A TileGrid that can switch between several 1-bit images, or hide."""

    def __init__(self, images, x, y, colour=0xFFFFFF):
        self.bitmaps = {k: bitmap(v) for k, v in images.items()}
        pal = displayio.Palette(2)
        pal[0] = 0
        pal.make_transparent(0)
        pal[1] = colour
        first = next(iter(self.bitmaps.values()))
        self.grid = displayio.TileGrid(first, pixel_shader=pal, x=x, y=y)
        self.state = None

    def show(self, key):
        if key == self.state:
            return
        self.state = key
        if key is None:
            self.grid.hidden = True
        else:
            self.grid.bitmap = self.bitmaps[key]
            self.grid.hidden = False
